"""Выбор ноги выхода среди включённых агрегаторов.

Два случая различаются положением сделки, а не техникой.

**Сразу после покупки** выход проверяется у назначенного продавца.
Маршрут только что выбран проходом по свежим котировкам обеих ног, и
опрашивать остальных значило бы тратить запросы на уже известное.

**У сделки, ушедшей в ожидание,** положение другое: назначение сделано
минуты или часы назад, деньги заперты в промежуточном токене, и лучшее
предложение вполне может оказаться у другого агрегатора. Поэтому
отложенная проверка спрашивает всех включённых и берёт лучшего
(``the_main_rules.md``, правило 21).

Прогноз, которым кандидаты здесь ранжируются, решением **не является**:
он считается по котировке и служит лишь тем, чтобы обязательство
спрашивать у лидера, а не у всех подряд. Продаём мы по обязательству —
его проверяет наблюдатель отдельно и у выбранного продавца.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from decimal import Decimal

from monik.domain.enums.providers import ProviderId
from monik.domain.models.quote import Quote
from monik.infrastructure.providers.contract import AggregatorAdapter, QuoteRequest

__all__ = ["ExitCandidate", "ExitQuote", "projected_output", "rank_exits"]


@dataclass(frozen=True, slots=True)
class ExitQuote:
    """Во что обойдётся выход из сделки прямо сейчас.

    Описание для **оператора**, а не для подсистемы: он спрашивает не
    «выгодно ли», а «сколько дадут», и порог выхода к этим числам не
    применяется.

    Числа — по **обязательству** агрегатора, а не по котировке. Человек
    решает, расставаться ли с деньгами, и видеть он должен то, что ему
    гарантированно отдадут, а не то, что пообещали.
    """

    t_id: str
    provider: str
    #: Сколько вернётся в базовом токене.
    output: Decimal
    #: Итог круга целиком: выручка минус вложенное минус газ.
    profit: Decimal
    symbol: str
    #: Удалось ли посчитать стоимость газа. Когда нет, ``profit``
    #: посчитан без неё и потому завышен: умолчать об этом нельзя
    #: (``CLAUDE.md`` §12).
    costs_known: bool = True


@dataclass(frozen=True, slots=True)
class ExitCandidate:
    """Один опрошенный выход.

    Запрос хранится вместе с котировкой намеренно: у каждой ноги свой
    допуск проскальзывания, и предложение потом собирается **тем же**
    запросом, каким получена котировка. Собрать его другим значило бы
    решать по одному, а исполнять другое.
    """

    provider_id: ProviderId
    adapter: AggregatorAdapter
    request: QuoteRequest
    quote: Quote
    #: Прогноз итога круга: котировка с поправкой на допуск этой ноги за
    #: вычетом её газа. Величина оценочная — обязательство спрашивается
    #: отдельно.
    projected_profit: int
    #: Известен ли был расход газа этой ноги. Неизвестный расход делает
    #: прогноз завышенным, и это важно не потерять: решение по такому
    #: кандидату всё равно примет проверка обязательства
    #: (``CLAUDE.md`` §12), но порядок опроса знать об этом должен.
    gas_known: bool = True
    #: Окупается ли нога хотя бы **без** газа. У неокупающейся прогноз
    #: посчитан по валовой разнице: газ ей не считали вовсе, потому что
    #: он может только ухудшить итог. Сравнивать такой прогноз с чистым
    #: нельзя, поэтому такие кандидаты уходят в конец списка.
    viable: bool = True


def projected_output(raw_output: int, *, slippage_bps: int) -> int:
    """Сколько нога обязалась бы отдать при своём допуске.

    Та же формула, по которой предельную сумму считает сам адаптер:
    прогноз должен быть сопоставим с обязательством, а не с рекламой.
    """
    return max(raw_output * (10_000 - slippage_bps) // 10_000, 1)


def rank_exits(candidates: Iterable[ExitCandidate]) -> tuple[ExitCandidate, ...]:
    """Кандидаты по убыванию прогноза.

    Не окупающийся даже без газа уходит в конец независимо от величины:
    его прогноз валовой, а у остальных чистый, и сравнивать их между
    собой — сравнивать разное.

    Кандидат с известным расходом газа идёт впереди равного ему с
    неизвестным: у второго прогноз завышен, и ставить его первым значило
    бы предпочитать неизвестность. При полном равенстве порядок задаёт
    идентификатор провайдера — два одинаковых такта обязаны выбрать
    одного и того же продавца.
    """
    return tuple(
        sorted(
            candidates,
            key=lambda item: (
                not item.viable,
                -item.projected_profit,
                not item.gas_known,
                item.provider_id.value,
            ),
        )
    )
